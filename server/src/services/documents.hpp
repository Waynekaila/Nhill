#pragma once
// One description of a sales document for every output (3.0.0). Nhill Business and
// Nhill POS print the same document from the same model: an invoice made at the till
// and an invoice made in Business share the template, the numbering sequence, the
// rounding rules and the wording. Two layouts render the model:
//   A4    — full page (print or PDF), used by default for invoices, credit notes,
//           quotes and orders;
//   ticket — 58 or 80 mm roll, used by default for till receipts.
// Every document can be produced in both layouts.
//
// Nothing here makes a document "fiscal": the notices of the compliance profile say what
// the document is (e.g. a management document that does not replace the standardised
// invoice of a fiscal device), and Nhill never claims a certification it does not have.
#include <optional>
#include <string>
#include <vector>

#include "pdf/pdf.hpp"
#include "services/common.hpp"

namespace nh::documents {

struct Model {
    std::string id, docType, status, lang, currency;
    bool draft = false, pos = false, walkIn = false;
    std::string title, number, watermark;
    std::string sellerName;
    std::vector<std::string> sellerLines;
    std::optional<std::string> logoBytes;
    std::string logoMime;
    std::string buyerLabel, buyerName;
    std::vector<std::string> buyerLines;
    std::vector<pdf::KV> meta;          // dates, status, currency, rate, origin, till details
    std::vector<std::string> columns;   // A4 table headers
    std::vector<pdf::Line> lines;
    std::vector<pdf::KV> totals;        // before the grand total
    pdf::KV grandTotal;
    std::string paymentsTitle;
    std::vector<pdf::KV> payments;      // "Cash · 28/10/2026" -> amount
    std::vector<pdf::KV> afterTotals;   // paid, credited, balance, change
    std::vector<std::string> notices;   // profile notices, mentions of the establishment
    std::vector<pdf::KV> footnotes;     // payment terms and details, notes
    std::string footer;                 // establishment footer (A4 bottom, ticket end)
    std::string closing;                // till message (tickets of the till)
    std::string generated;              // "Generated by Nhill · Fingerprint …"
    std::string pageLabel;
    std::string creationDateIso;        // fixed PDF date -> deterministic output
    float ticketWidthMm = 80;           // register setting for till documents
};

Model build(Env& env, db::Tx& tx, const std::string& documentId);
std::string renderA4(Env& env, const Model& m);
std::string renderTicket(Env& env, const Model& m, std::optional<float> widthMm = std::nullopt);
// Layout requested by ?format=a4|ticket (default: ticket for till receipts, A4 otherwise).
std::string render(Env& env, const Model& m, const std::optional<std::string>& format,
                   const std::optional<std::string>& width);
// Everything the layouts print, for parity tests and support (no binary data).
json toJson(const Model& m);

}  // namespace nh::documents
