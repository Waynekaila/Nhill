#!/usr/bin/env python3
"""Generates client/src/core/countries_data.inc: the 249 ISO 3166-1 alpha-2 countries
with their French and English names and their main legal-tender currency, from the
Unicode CLDR data shipped with Babel (pip package "Babel"). Re-run after a Babel update:

    python3 scripts/tools/gen-countries.py > client/src/core/countries_data.inc

CLDR also lists codes that are not ISO 3166-1 country codes (EU, UN, XK, AC, IC...):
they are excluded below.
"""
import babel
from babel import Locale
from babel.numbers import get_territory_currencies

EXCLUDED = {"EU", "EZ", "UN", "QO", "XA", "XB", "ZZ", "XK", "AC", "CP", "CQ", "DG", "EA", "IC", "TA"}


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    fr, en = Locale("fr").territories, Locale("en").territories
    codes = sorted(k for k in en if len(k) == 2 and k.isalpha() and k.isupper() and k not in EXCLUDED)
    assert len(codes) == 249, len(codes)
    print(f"// Generated by scripts/tools/gen-countries.py from Unicode CLDR (Babel {babel.__version__}). Do not edit.")
    print("// ISO 3166-1 alpha-2 code, French name, English name, main legal tender (ISO 4217, empty if none).")
    for k in codes:
        cur = get_territory_currencies(k, tender=True)
        print(f"{{{c(k)}, {c(fr[k])}, {c(en[k])}, {c(cur[0] if cur else '')}}},")


if __name__ == "__main__":
    main()
